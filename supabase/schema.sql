-- ------------------------------------------------------------------
-- Part 3: product colour variants (real commerce variant system).
-- See scripts/sql/variants.sql for the full migration + seed.
--
-- images[] is the colour's OWN photography. An EMPTY array means the colour is
-- not photographed yet: the storefront greys its swatch as "photography
-- pending" and never falls back to another colour's photo.
-- ------------------------------------------------------------------
create table if not exists public.product_variants (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products(id) on delete cascade,
  color_name  text        not null,
  color_hex   text        not null,
  sku         text,
  stock       integer     not null default 0,
  price       numeric(10, 2),
  sizes       text[]      not null default '{XS,S,M,L,XL}',
  images      text[]      not null default '{}',
  hidden      boolean     not null default false,
  position    integer     not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists product_variants_product_idx
  on public.product_variants (product_id, position);

alter table public.product_variants enable row level security;

drop policy if exists "public read variants"  on public.product_variants;
drop policy if exists "admin read variants"   on public.product_variants;
drop policy if exists "admin write variants"  on public.product_variants;

create policy "public read variants" on public.product_variants
  for select using (hidden = false);
create policy "admin read variants" on public.product_variants
  for select to authenticated using (true);
create policy "admin write variants" on public.product_variants
  for all to authenticated using (true) with check (true);


-- ------------------------------------------------------------------
-- Part 4: fitting requests (the atelier's appointment book).
-- See scripts/sql/fittings.sql for the standalone migration.
--
-- A booking is not an order: no price, no colour, no stock. Anonymous visitors
-- may INSERT (they have no account); only signed-in admins may read or update.
-- ------------------------------------------------------------------
create table if not exists public.fitting_requests (
  id             bigint generated by default as identity primary key,
  name           text        not null,
  email          text        not null,
  phone          text,
  service        text        not null,
  preferred_date date,
  notes          text,
  status         text        not null default 'New',
  created_at     timestamptz not null default now()
);

create index if not exists fitting_requests_created_at_idx
  on public.fitting_requests (created_at desc);

alter table public.fitting_requests enable row level security;

drop policy if exists "public create fitting requests" on public.fitting_requests;
drop policy if exists "admin read fitting requests"    on public.fitting_requests;
drop policy if exists "admin update fitting requests"  on public.fitting_requests;

