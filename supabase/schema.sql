create table if not exists public.products (
  id             bigint generated by default as identity primary key,
  sku            text unique,
  name           text        not null,
  collection     text        not null,
  price          numeric(10, 2) not null default 0,
  currency       text        not null default 'USD',
  image          text        not null default '',
  alt            text        not null default '',
  tag            text,
  description    text,                      -- owner-written; storefront falls back to a generated line
  archived       boolean     not null default false,   -- hidden from the shop, kept for orders
  fabric         text,                      -- Ankara / Adire / Aso-Oke / ...
  origin         text,
  care_notes     text,
  inventory      integer     not null default 0,
  inquiry_only   boolean     not null default false,   -- wholesale path
  min_qty        integer     not null default 1,
  related_ids    bigint[],                   -- owner-chosen related pieces, in order
  created_at     timestamptz not null default now()
);

create table if not exists public.lookbook (
  id         bigint generated by default as identity primary key,
  number     text        not null,
  image      text        not null default '',
  alt        text        not null default '',
  slot       text,                        -- media-manager slot id
  position   integer     not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id             bigint generated by default as identity primary key,
  reference      text        not null unique,
  customer       text        not null,
  email          text,
  phone          text,
  address        text,
  note           text,
  product        text,
  status         text        not null default 'Processing',
  -- Manual bank transfer: no gateway is called, so an order is born
  -- 'pending-payment' and stays there until the atelier marks it paid.
  payment_status text        not null default 'pending-payment',
  payment_method text        not null default 'bank-transfer',
  -- What the customer was told to pay into, frozen at order time.
  bank_details   jsonb,
  items          jsonb       not null default '[]'::jsonb,
  subtotal       numeric(10, 2) not null default 0,
  shipping       numeric(10, 2) not null default 0,
  total          numeric(10, 2) not null default 0,
  currency       text        not null default 'USD',
  type           text        not null default 'retail',    -- retail | wholesale
  qty            integer     not null default 1,
  created_at     timestamptz not null default now()
);

create table if not exists public.settings (
  id                  integer primary key default 1,
  store_name          text not null default 'AVID WOMAN VOGUE',
  contact_email       text,
  order_notifications text,
  currency            text not null default 'USD',
  -- Where clients pay (manual bank transfer). Editable any time in the admin
  -- console; her save is live on the checkout page immediately.
  bank_name           text,
  account_number      text,
  account_name        text,
  instagram           text,
  facebook            text,
  tiktok              text,
  updated_at          timestamptz not null default now(),
  constraint settings_singleton check (id = 1)
);

