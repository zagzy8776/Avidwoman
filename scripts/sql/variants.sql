-- MIGRATION: product colour variants (real commerce variant system).
-- Each colour is a record with its own images, SKU, stock and sizes.
-- Applied on top of schema.sql; safe to re-run (idempotent).

create table if not exists public.product_variants (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products(id) on delete cascade,
  color_name  text        not null,
  color_hex   text        not null,
  sku         text,
  stock       integer     not null default 0,
  price       numeric(10, 2),
  sizes       text[]      not null default '{XS,S,M,L,XL}',
  images      text[]      not null default '{}',
  hidden      boolean     not null default false,
  position    integer     not null default 0,
  created_at  timestamptz not null default now()
);

create index if not exists product_variants_product_idx
  on public.product_variants (product_id, position);

alter table public.product_variants enable row level security;

drop policy if exists "public read variants"  on public.product_variants;
drop policy if exists "admin read variants"   on public.product_variants;
drop policy if exists "admin write variants"  on public.product_variants;

create policy "public read variants" on public.product_variants
  for select using (hidden = false);
create policy "admin read variants" on public.product_variants
  for select to authenticated using (true);
create policy "admin write variants" on public.product_variants
  for all to authenticated using (true) with check (true);


