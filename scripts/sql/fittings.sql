-- ------------------------------------------------------------------
-- FITTING REQUESTS — the atelier's appointment book.
--
--   node scripts/sql.mjs scripts/sql/fittings.sql
--
--   (equivalent to pasting this file into the Supabase SQL editor)
--
-- WHY A SEPARATE TABLE: a shopper books an APPOINTMENT, not a product. It has
-- no price, no colour and no stock, so it must not be squeezed into `orders`
-- where every row is expected to carry money. This is what makes the house
-- bookable: a tailor is booked, not browsed.
--
-- SAFE TO RE-RUN: table/index are IF NOT EXISTS and every policy is dropped
-- before it is created.
-- ------------------------------------------------------------------

create table if not exists public.fitting_requests (
  id             bigint generated by default as identity primary key,
  name           text        not null,
  email          text        not null,
  phone          text,
  service        text        not null,
  preferred_date date,
  notes          text,
  status         text        not null default 'New',
  created_at     timestamptz not null default now()
);

create index if not exists fitting_requests_created_at_idx
  on public.fitting_requests (created_at desc);

alter table public.fitting_requests enable row level security;

drop policy if exists "public create fitting requests" on public.fitting_requests;
drop policy if exists "admin read fitting requests"    on public.fitting_requests;
drop policy if exists "admin update fitting requests"  on public.fitting_requests;

-- INSERT ONLY for the storefront. There is deliberately no anon SELECT policy:
-- a shopper must never be able to read another shopper's booking, and the
-- server action does not need the row back (it never calls .select()).
create policy "public create fitting requests" on public.fitting_requests
  for insert to anon, authenticated with check (true);

create policy "admin read fitting requests" on public.fitting_requests
  for select to authenticated using (true);

create policy "admin update fitting requests" on public.fitting_requests
  for update to authenticated using (true) with check (true);
